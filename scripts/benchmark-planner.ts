import { mkdirSync, writeFileSync } from "node:fs";
import { performance } from "node:perf_hooks";
import { frozenLagosBundle } from "../src/bundle/loadFrozenBundle";
import { optimizePackage } from "../src/planning/packageOptimizer";

const brief = {
  productName: "Planner benchmark",
  productDescription: "Convenience launch for students, young workers, and shoppers",
  targetAudience: "Students, young workers, and convenience shoppers",
  sector: "fmcg" as const,
  objective: "broad_reach" as const,
  daypart: "pm" as const,
  budgetNgn: 100_000_000,
  normalizationBudgetNgn: 150_000_000,
  flightStart: "2026-09-01",
  flightEnd: "2026-09-28",
};

function scaledBundle(siteCount: number) {
  const bundle = structuredClone(frozenLagosBundle);
  const original = bundle.sites;
  bundle.sites = Array.from({ length: siteCount }, (_, index) => {
    const source = structuredClone(original[index % original.length]);
    const cycle = Math.floor(index / original.length);
    return {
      ...source,
      id: `${source.id}-benchmark-${index}`,
      label: `${source.label} benchmark ${index}`,
      supplierId: `benchmark-supplier-${index % 12}`,
      coordinate: [
        source.coordinate[0] + cycle * 0.00002,
        source.coordinate[1] + cycle * 0.00002,
      ] as [number, number],
      rateNgn: source.rateNgn + (index % 7) * 10_000,
    };
  });
  return bundle;
}

type Result = {
  siteCount: number;
  durationMs: number;
  heapDeltaMb: number;
  recommendedSiteCount: number;
};

function run(siteCount: number): Result {
  const bundle = scaledBundle(siteCount);
  const heapBefore = process.memoryUsage().heapUsed;
  const start = performance.now();
  const result = optimizePackage(bundle, brief);
  const durationMs = performance.now() - start;
  const heapDeltaMb = Math.max(
    0,
    (process.memoryUsage().heapUsed - heapBefore) / 1024 / 1024,
  );
  return {
    siteCount,
    durationMs,
    heapDeltaMb,
    recommendedSiteCount: result.recommended.siteIds.length,
  };
}

const results = [run(50), run(100)];
const hundred = results.find((result) => result.siteCount === 100)!;
const latencyLimitMs = 2_000;
const heapDeltaLimitMb = 256;
const passed =
  hundred.durationMs <= latencyLimitMs &&
  hundred.heapDeltaMb <= heapDeltaLimitMb;

const table = results.map((result) =>
  `| ${result.siteCount} | ${result.durationMs.toFixed(1)} ms | ${result.heapDeltaMb.toFixed(1)} MB | ${result.recommendedSiteCount} |`,
).join("\n");

const markdown = `# Planner performance benchmark\n\n` +
  `Generated by \`pnpm tsx scripts/benchmark-planner.ts\` on Node ${process.version}.\n\n` +
  `This benchmark exercises the **full bounded optimizer**, not only shortlist generation. ` +
  `The synthetic inventory keeps the frozen Lagos target/panel contract and expands only the site inventory.\n\n` +
  `| Inventory | Wall clock | Heap delta | Recommended sites |\n` +
  `|---:|---:|---:|---:|\n${table}\n\n` +
  `## Guardrail\n\n` +
  `For the current deterministic demo engine, a 100-site run must complete within **${latencyLimitMs} ms** ` +
  `and add no more than **${heapDeltaLimitMb} MB** of heap in the benchmark process.\n\n` +
  `Result: **${passed ? "PASS" : "FAIL"}**.\n\n` +
  `This is a regression guardrail, not a production SLA. Browser/device latency and larger real-world panels must be measured separately.\n`;

mkdirSync("docs", { recursive: true });
writeFileSync("docs/planner-performance.md", markdown, "utf8");
console.log(JSON.stringify({ results, latencyLimitMs, heapDeltaLimitMb, passed }));

if (!passed) process.exitCode = 1;
